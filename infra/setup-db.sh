#!/bin/bash
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive
echo "STEP disable apt timers"
systemctl disable --now apt-daily.timer apt-daily-upgrade.timer 2>/dev/null || true
echo "STEP apt postgresql-common"
apt-get update -y
apt-get install -y postgresql-common ca-certificates curl gnupg sysstat
echo "STEP pgdg repo"
/usr/share/postgresql-common/pgdg/apt.postgresql.org.sh -y
echo "STEP install postgresql-18"
apt-get install -y postgresql-18 postgresql-contrib-18
echo "STEP config"
install -d -o postgres -g postgres /etc/postgresql/18/main/conf.d
install -o postgres -g postgres -m 644 /root/pg-limit/pg-limit.conf /etc/postgresql/18/main/conf.d/pg-limit.conf
install -o postgres -g postgres -m 640 /root/pg-limit/pg_hba.conf /etc/postgresql/18/main/pg_hba.conf
echo "STEP restart"
systemctl restart postgresql
systemctl is-active postgresql
echo "STEP role and database"
sudo -u postgres psql -q -v ON_ERROR_STOP=1 -v pass="$(cat /root/pg-limit/db.pass)" > /root/pg-limit/create-role.log 2>&1 <<'SQL'
SELECT format('CREATE ROLE bench LOGIN PASSWORD %L', :'pass') \gexec
SELECT 'CREATE DATABASE social OWNER bench' WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = 'social') \gexec
SQL
chmod 600 /root/pg-limit/create-role.log
echo "role_exit=$?"
sudo -u postgres psql -d social -v ON_ERROR_STOP=1 <<'SQL'
CREATE EXTENSION IF NOT EXISTS pg_stat_statements;
CREATE TABLE IF NOT EXISTS users (
  id bigint NOT NULL,
  username text NOT NULL,
  created_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS posts (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id bigint NOT NULL,
  body text NOT NULL,
  created_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS likes (
  post_id bigint NOT NULL,
  user_id bigint NOT NULL,
  created_at timestamptz NOT NULL
);
ALTER TABLE users OWNER TO bench;
ALTER TABLE posts OWNER TO bench;
ALTER TABLE likes OWNER TO bench;
SQL
echo "STEP listen"
ss -lnt | awk '$4 ~ /:5432$/'
/usr/lib/postgresql/18/bin/postgres -V
echo "STEP done"
